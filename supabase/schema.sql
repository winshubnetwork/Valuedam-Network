-- Optional database schema for quote requests.
-- Run this in Supabase SQL Editor when you are ready to store quote requests.

create table if not exists public.quote_requests (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  name text not null,
  business text,
  email text not null,
  phone text not null,
  service text not null,
  budget text,
  timeline text,
  message text not null,
  status text default 'new'
);

alter table public.quote_requests enable row level security;

-- Public visitors can submit quote requests.
create policy "Anyone can submit quote requests"
on public.quote_requests
for insert
to anon, authenticated
with check (true);

-- Do NOT create a public SELECT policy.
-- Admin viewing should be implemented with authenticated admin access in V2.
